"""Write knowledge/matchups_source.md from pro lane records only (no hand-written counters), then grade it with check_matchups.py.

  python3 tools/build_matchups_from_pro.py && python3 tools/check_matchups.py

For every champion in a lane (top, mid, bot, support), a counter is listed when pros played the matchup 20+ times (raw), 15+ weighted
games (pro_data/lane_h2h.json, patch and level weighted), and the counter's smoothed weighted win rate is 0.57+ (3 wins + 3 losses
added). That is the same bar tools/augment_matchups.py uses for its "(pro-data add)" entries. Up to 5 counters per champion, best
first. Jungle is left empty: jungle head-to-heads are not a lane, and the draft tools weigh them less.
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from common import ROOT
from knowledge import to_id, display, tags

H2H = json.load(open(os.path.join(ROOT, "pro_data", "lane_h2h.json"), encoding="utf-8"))
MIN_RAW, MIN_W, MIN_WR, PER_ROW = 20, 15, 0.57, 5

def counters(role):
    out = {}
    for r in H2H.get(role, []):
        a, b = to_id(r["a"]), to_id(r["b"])
        if not a or not b or a not in tags() or b not in tags(): continue
        wg = r.get("wg", r["games"]); wa = r.get("wa", r["a_wins"]); g = r["games"]
        if g < MIN_RAW or wg < MIN_W: continue
        for tgt, ctr, ww, w in ((a, b, wg - wa, g - r["a_wins"]), (b, a, wa, r["a_wins"])):
            s = (ww + 3) / (wg + 6)
            if s >= MIN_WR: out.setdefault(tgt, []).append((s, ctr, w, g))
    return {t: sorted(v, reverse=True)[:PER_ROW] for t, v in out.items()}

SECTIONS = [("Top", "top", "Champion"), ("Jungle (no direct lane)", "jungle", "Champion"), ("Mid", "mid", "Champion"),
            ("Bot", "bot", "ADC"), ("Support", "support", "Champion")]
L = ["# Lane counters from pro lane records", "",
     f"Generated by `tools/build_matchups_from_pro.py` from `pro_data/lane_h2h.json` only: a counter has {MIN_RAW}+ pro games in that lane "
     f"({MIN_W}+ weighted) and a smoothed win rate of {MIN_WR:.2f}+. No hand-written counters. `tools/check_matchups.py` grades them into `matchups.md`.", ""]
n = 0
for title, role, col in SECTIONS:
    L += [f"## {title}", f"| {col} | Good counters | Why |", "|---|---|---|"]
    if role != "jungle":
        for tgt, cs in sorted(counters(role).items(), key=lambda kv: display(kv[0])):
            L.append(f"| {display(tgt)} | " + ", ".join(display(c) for _, c, _, _ in cs) + " | Pro lane record: "
                     + "; ".join(f"{display(c)} {w}-{g - w}" for _, c, w, g in cs) + " |")
            n += len(cs)
    L.append("")
open(os.path.join(ROOT, "knowledge", "matchups_source.md"), "w", encoding="utf-8").write("\n".join(L))
print(n, "counters written to knowledge/matchups_source.md")
